/* Replacement thermal printer bridge injected after the worker template at build time. */
function bridgeScript(settings, siteOrigin) {
  return [
    "# Conector de impressão Açailandia PE — bobina térmica de 80 mm",
    "$Site = '" + ps(siteOrigin) + "'",
    "$Chave = '" + ps(settings.print_bridge_key) + "'",
    "$ImpressoraCaixa = '" + ps(settings.reception_printer) + "'",
    "$ImpressoraCozinha = '" + ps(settings.kitchen_printer) + "'",
    "$Headers = @{ 'X-Print-Key' = $Chave }",
    "$LogoUri = 'https://storage.googleapis.com/prod-cardapio-web/uploads/company/logo/14701/9f065ffdREQUISITOS_RV__4_.png'",
    "$LogoPath = Join-Path $env:LOCALAPPDATA 'Acailandia\logo.png'",
    "Add-Type -AssemblyName System.Drawing",
    "try {",
    "  [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12",
    "  $LogoFolder = Split-Path -Parent $LogoPath",
    "  if (-not (Test-Path $LogoFolder)) { New-Item -ItemType Directory -Path $LogoFolder -Force | Out-Null }",
    "  if (-not (Test-Path $LogoPath)) { Invoke-WebRequest -Uri $LogoUri -OutFile $LogoPath -UseBasicParsing -TimeoutSec 15 }",
    "} catch { Write-Warning 'Não foi possível baixar a logo; o recibo será impresso com o nome da loja.' }",
    "function Get-TicketLines {",
    "  param([string]$Conteudo)",
    "  $Resultado = New-Object System.Collections.Generic.List[string]",
    "  foreach ($TextoOriginal in ($Conteudo -split '\r?\n')) {",
    "    $Texto = $TextoOriginal.TrimEnd()",
    "    if ($Texto.Length -eq 0) { $Resultado.Add(''); continue }",
    "    while ($Texto.Length -gt 33) {",
    "      $Corte = $Texto.LastIndexOf(' ',33)",
    "      if ($Corte -lt 1) { $Corte = 33 }",
    "      $Resultado.Add($Texto.Substring(0,$Corte).TrimEnd())",
    "      $Texto = $Texto.Substring($Corte).TrimStart()",
    "    }",
    "    $Resultado.Add($Texto)",
    "  }",
    "  return $Resultado.ToArray()",
    "}",
    "function Get-BrandLogo {",
    "  if (-not (Test-Path $LogoPath)) { return $null }",
    "  $Source = $null",
    "  try {",
    "    $Source = [System.Drawing.Bitmap]::FromFile($LogoPath)",
    "    $Mono = New-Object System.Drawing.Bitmap($Source.Width,$Source.Height,[System.Drawing.Imaging.PixelFormat]::Format24bppRgb)",
    "    $Background = $Source.GetPixel(0,0)",
    "    for ($Y=0; $Y -lt $Source.Height; $Y++) { for ($X=0; $X -lt $Source.Width; $X++) {",
    "      $Pixel = $Source.GetPixel($X,$Y)",
    "      $Distance = [Math]::Abs([int]$Pixel.R-[int]$Background.R)+[Math]::Abs([int]$Pixel.G-[int]$Background.G)+[Math]::Abs([int]$Pixel.B-[int]$Background.B)",
    "      $Color = if ($Pixel.A -lt 80 -or $Distance -lt 105) { [System.Drawing.Color]::White } else { [System.Drawing.Color]::Black }",
    "      $Mono.SetPixel($X,$Y,$Color)",
    "    } }",
    "    return $Mono",
    "  } catch { return $null } finally { if ($Source) { $Source.Dispose() } }",
    "}",
    "function Print-Ticket {",
    "  param([string]$Conteudo,[string]$NomeImpressora)",
    "  $Documento = New-Object System.Drawing.Printing.PrintDocument",
    "  $Documento.PrinterSettings.PrinterName = $NomeImpressora",
    "  if (-not $Documento.PrinterSettings.IsValid) { throw 'Impressora não encontrada: ' + $NomeImpressora }",
    "  $script:JWPrintLines = @(Get-TicketLines $Conteudo)",
    "  $AlturaPapel = [Math]::Max(560,[Math]::Min(5200,($script:JWPrintLines.Count * 28) + 300))",
    "  $Papel = New-Object System.Drawing.Printing.PaperSize('Bobina 80mm',315,$AlturaPapel)",
    "  $Documento.DefaultPageSettings.PaperSize = $Papel",
    "  $Documento.DefaultPageSettings.Margins = New-Object System.Drawing.Printing.Margins(18,18,8,8)",
    "  $Documento.OriginAtMargins = $true",
    "  $script:JWPrintPosition = 0",
    "  $Documento.add_PrintPage({",
    "    param($Remetente,$Evento)",
    "    $Normal = New-Object System.Drawing.Font('Arial',10)",
    "    $Destaque = New-Object System.Drawing.Font('Arial',10,[System.Drawing.FontStyle]::Bold)",
    "    $Titulo = New-Object System.Drawing.Font('Arial',13,[System.Drawing.FontStyle]::Bold)",
    "    $Esquerda = New-Object System.Drawing.StringFormat",
    "    $Centro = New-Object System.Drawing.StringFormat; $Centro.Alignment = [System.Drawing.StringAlignment]::Center",
    "    $Y = 0",
    "    $Logo = Get-BrandLogo",
    "    if ($Logo) {",
    "      $LogoWidth = [Math]::Min(100,$Evento.MarginBounds.Width)",
    "      $LogoHeight = [Math]::Min(82,($Logo.Height * $LogoWidth / $Logo.Width))",
    "      $LogoWidth = $Logo.Width * $LogoHeight / $Logo.Height",
    "      $LogoX = [Math]::Max(0,($Evento.MarginBounds.Width-$LogoWidth)/2)",
    "      $Evento.Graphics.DrawImage($Logo,$LogoX,$Y,$LogoWidth,$LogoHeight)",
    "      $Y += $LogoHeight + 5",
    "      $Logo.Dispose()",
    "    }",
    "    while ($script:JWPrintPosition -lt $script:JWPrintLines.Count) {",
    "      $Texto = $script:JWPrintLines[$script:JWPrintPosition]",
    "      $Cabecalho = $script:JWPrintPosition -eq 0 -or $Texto -match '^(\*\*\*|Pedido:|TOTAL:)'",
    "      $Fonte = if ($script:JWPrintPosition -eq 0) { $Titulo } elseif ($Cabecalho) { $Destaque } else { $Normal }",
    "      $Formato = if ($script:JWPrintPosition -eq 0 -or $Texto -match '^\*\*\*') { $Centro } else { $Esquerda }",
    "      $AlturaLinha = $Fonte.GetHeight($Evento.Graphics) + 2",
    "      if (($Y + $AlturaLinha) -gt $Evento.MarginBounds.Height) { break }",
    "      $Evento.Graphics.DrawString($Texto,$Fonte,[System.Drawing.Brushes]::Black,0,$Y,$Formato)",
    "      $Y += $AlturaLinha; $script:JWPrintPosition++",
    "    }",
    "    $Evento.HasMorePages = $script:JWPrintPosition -lt $script:JWPrintLines.Count",
    "    $Normal.Dispose(); $Destaque.Dispose(); $Titulo.Dispose(); $Esquerda.Dispose(); $Centro.Dispose()",
    "  })",
    "  try { $Documento.Print() } finally { $Documento.Dispose() }",
    "}",
    "Write-Host 'Conector Açailandia PE iniciado. Pressione Ctrl+C para encerrar.'",
    "while ($true) {",
    "  try {",
    "    $Resposta = Invoke-RestMethod -Uri ($Site + '/api/print/jobs') -Headers $Headers -Method Get",
    "    foreach ($Job in $Resposta.jobs) {",
    "      if ($Job.target -eq 'kitchen' -and $ImpressoraCozinha -eq $ImpressoraCaixa) {",
    "        Invoke-RestMethod -Uri ($Site + '/api/print/jobs/' + $Job.id) -Headers $Headers -Method Patch -ContentType 'application/json' -Body '{\"status\":\"printed\"}' | Out-Null",
    "        continue",
    "      }",
    "      $Impressora = if ($Job.target -eq 'kitchen') { $ImpressoraCozinha } else { $ImpressoraCaixa }",
    "      try {",
    "        Print-Ticket -Conteudo $Job.ticket -NomeImpressora $Impressora",
    "        Invoke-RestMethod -Uri ($Site + '/api/print/jobs/' + $Job.id) -Headers $Headers -Method Patch -ContentType 'application/json' -Body '{\"status\":\"printed\"}' | Out-Null",
    "        Write-Host ('Impresso: ' + $Job.order_id + ' - ' + $Job.target)",
    "      } catch {",
    "        Invoke-RestMethod -Uri ($Site + '/api/print/jobs/' + $Job.id) -Headers $Headers -Method Patch -ContentType 'application/json' -Body '{\"status\":\"failed\"}' | Out-Null",
    "        Write-Warning ('Falha na impressora ' + $Impressora + ': ' + $_.Exception.Message)",
    "      }",
    "    }",
    "  } catch { Write-Warning ('Sem conexão com o site: ' + $_.Exception.Message) }",
    "  Start-Sleep -Seconds 5",
    "}",
    ""
  ].join("\r\n");
}
